"""Validate the canonical evidence and regenerate static browser/CSV artifacts."""
import csv
import io
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent


def build():
    data = json.loads((HERE / 'evidence.json').read_text())
    sources = {s['id']: s for s in data['sources']}
    ids = set()
    for row in data['observations']:
        assert row['id'] not in ids, row['id']
        ids.add(row['id'])
        assert row['source'] in sources
        assert row['date'] <= data['cutoff']
        assert 0 <= row['value'] <= 1
        assert row['metric'] in ('recall', 'auroc')
        if row['metric'] == 'recall':
            assert 0 < row['fpr'] < 1
            assert row['negative_reference']
        if row.get('n_positive') is not None:
            assert 0 <= row['caught'] <= row['n_positive']
            assert abs(row['value'] - row['caught']/row['n_positive']) < 1e-12
        assert row['locator'] and row['unit'] and row['scope']
    for event in data['history']:
        assert event['source'] in sources
    js = '/* Generated by analysis/interpretability/build.py. */\nwindow.INTERPRETABILITY_DATA = '
    (ROOT / 'interpretability_data.js').write_text(js + json.dumps(data, indent=2, ensure_ascii=False) + ';\n')
    fields = ['id', 'date', 'date_basis', 'source', 'locator', 'scope', 'task', 'model',
              'model_parameters_b', 'method', 'metric', 'value', 'fpr', 'negative_reference',
              'unit', 'n_positive', 'caught', 'precision', 'note']
    stream = io.StringIO()
    writer = csv.DictWriter(stream, fields, extrasaction='ignore', lineterminator='\n')
    writer.writeheader()
    writer.writerows(data['observations'])
    (HERE / 'observations.csv').write_text(stream.getvalue())
    print(f"Validated {len(data['observations'])} observations and {len(sources)} primary sources; generated JS and CSV.")


if __name__ == '__main__':
    build()
